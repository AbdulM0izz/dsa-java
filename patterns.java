public class patterns {

    public static void main(String[] args) {

        // Solid square pattern
         int n = 4;

         for ( int row = 1; row <= n; row++) {
             // for column inner loop
             for (int column = 1; column <= n; column++) {
                 System.out.print("* ");
             }
             System.out.println();
         }












    }
}

